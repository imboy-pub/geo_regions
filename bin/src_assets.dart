/// Shared infrastructure for the `bin/assets.dart` CLI (P1-06).
///
/// Split out of `assets.dart` to keep both files under the repository's
/// 800-line limit. Contents: exit-code contract, [CliError], the output
/// guard (`guard_output` semantics from the Python golden reference), the
/// precise pubspec fragment writer, the sorted-key pretty JSON writer and
/// the atomic staging swap. Pure `dart:io`/`dart:convert`; no package
/// imports so the CLI stays runnable on the plain Dart VM.
///
/// Behaviour is aligned with the Python golden reference
/// `tool/geo_data.py::build_offline` + `guard_output`.
library;

import 'dart:io';

import 'package:geo_regions/src/canonical.dart' show compareJsonKeys;

/// Unexpected internal failure.
const int kExitUnexpected = 1;

/// Config, usage or environment precondition error.
const int kExitConfig = 2;

/// Missing, stale or corrupt resource.
const int kExitResource = 3;

/// Unsafe or protected output.
const int kExitOutput = 4;

/// Package whose data this tool bundles; resolved via package_config.
const String kPackageName = 'geo_regions';

/// Generation marker guarding `--replace` (replace-protection contract).
const String kMarkerName = '.geo_regions_generation';

/// Prefix of every generated pubspec asset entry: Flutter resolves
/// `packages/<pkg>/...` entries in a host pubspec against the installed
/// package (flutter_tools `_resolvePackageAsset`).
const String kAssetPrefix = 'packages/$kPackageName/data';

const String kManifestName = 'manifest.json';
const String kRegistryName = 'registry.json';

/// Package source trees the output must never overlap.
const List<String> kProtectedPackageTrees = <String>[
  'data',
  'sources',
  'tool',
  'schemas',
  'docs',
];

/// Fatal CLI failure carrying the process exit code.
final class CliError implements Exception {
  final int code;
  final String message;

  const CliError(this.code, this.message);

  @override
  String toString() => message;
}

/// Applies `guard_output` semantics to the requested output directory and
/// returns the normalized absolute path.
///
/// Rejections (all [CliError] with [kExitOutput]): `.`/`..` components,
/// symlink anywhere in the output's ancestor chain, filesystem root or home
/// directory, the package root itself, overlap with the package source
/// trees, being an ancestor of the package root, an existing non-directory,
/// an existing directory without `--replace`, and `--replace` without the
/// generation marker.
String guardOutput(String rawOutput, String packageRoot, bool replace) {
  final output = _normalizeOutputPath(rawOutput);
  _rejectSymlinkAncestors(output);
  _rejectUnsafeOutput(output, packageRoot);
  final dir = Directory(output);
  if (dir.existsSync()) {
    if (dir.statSync().type != FileSystemEntityType.directory) {
      throw const CliError(kExitOutput, 'output exists and is not a directory');
    }
    if (!replace) {
      throw CliError(
        kExitOutput,
        'output already exists: $output; re-run with --replace (replacement '
        'additionally requires the $kMarkerName marker written by this tool)',
      );
    }
    if (!File('$output/$kMarkerName').existsSync()) {
      throw CliError(
        kExitOutput,
        'refusing to replace $output: no $kMarkerName marker; the directory '
        'was not generated by this tool',
      );
    }
  }
  Directory(parentOf(output)).createSync(recursive: true);
  return output;
}

String _normalizeOutputPath(String raw) {
  final trimmed = raw.trim();
  if (trimmed.isEmpty) {
    throw const CliError(kExitOutput, 'output path is empty');
  }
  final candidate = trimmed.startsWith('/')
      ? trimmed
      : '${Directory.current.path}/$trimmed';
  final parts = candidate.split('/');
  for (final part in parts) {
    if (part == '.' || part == '..') {
      throw CliError(
        kExitOutput,
        "output path must not contain '.' or '..' components: $raw",
      );
    }
  }
  return '/${parts.where((part) => part.isNotEmpty).join('/')}';
}

void _rejectSymlinkAncestors(String path) {
  var current = path;
  while (true) {
    if (FileSystemEntity.isLinkSync(current)) {
      throw CliError(kExitOutput, 'output path contains symlink: $current');
    }
    final parent = parentOf(current);
    if (parent == current) {
      return;
    }
    current = parent;
  }
}

void _rejectUnsafeOutput(String output, String packageRoot) {
  if (output == '/') {
    throw const CliError(
      kExitOutput,
      'unsafe output: must not be the filesystem root',
    );
  }
  final home = Platform.environment['HOME'];
  if (home != null && home.isNotEmpty && output == home) {
    throw CliError(
      kExitOutput,
      'unsafe output: must not be the home directory ($home)',
    );
  }
  if (output == packageRoot) {
    throw CliError(
      kExitOutput,
      'unsafe output: must not be the package root ($packageRoot)',
    );
  }
  for (final name in kProtectedPackageTrees) {
    final tree = '$packageRoot/$name';
    if (isWithin(output, tree)) {
      throw CliError(
        kExitOutput,
        'unsafe output: must not overlap the package source tree $tree/ '
        '($output)',
      );
    }
  }
  if (isWithin(packageRoot, output)) {
    throw CliError(
      kExitOutput,
      'unsafe output: $output is an ancestor of the package root '
      '$packageRoot; generated files must live outside it',
    );
  }
}

/// Whether [path] equals or lives under [ancestor] (both absolute, lexical).
bool isWithin(String path, String ancestor) =>
    path == ancestor || path.startsWith('$ancestor/');

/// Parent directory of an absolute POSIX-style path; root's parent is root.
String parentOf(String path) {
  final index = path.lastIndexOf('/');
  return index <= 0 ? '/' : path.substring(0, index);
}

/// Precise per-file pubspec asset entries (PRD §7.3): the host merges these
/// lines into its existing `flutter:` block; no directory lines are emitted
/// because Flutter directory declarations do not recurse.
String fragmentYaml(List<String> assetPaths) {
  final buffer = StringBuffer()
    ..writeln(
      "# Merge assets into the host's EXISTING flutter: block; "
      'do not create a second block.',
    )
    ..writeln('flutter:')
    ..writeln('  assets:');
  for (final relative in assetPaths) {
    buffer.writeln('    - "$kAssetPrefix/$relative"');
  }
  return buffer.toString();
}

/// Pretty JSON with recursively sorted keys and literal UTF-8 — the Dart
/// counterpart of `tool/geo_data.py::write_json` (trailing newline).
void writeJsonFile(String path, Object? value) {
  final buffer = StringBuffer();
  _writeJson(buffer, value, 0);
  buffer.writeln();
  File(path).writeAsStringSync(buffer.toString());
}

void _writeJson(StringBuffer buffer, Object? value, int depth) {
  if (value == null) {
    buffer.write('null');
  } else if (value is bool) {
    buffer.write(value ? 'true' : 'false');
  } else if (value is int) {
    buffer.write(value);
  } else if (value is String) {
    _writeJsonString(buffer, value);
  } else if (value is List<Object?>) {
    _writeJsonList(buffer, value, depth);
  } else if (value is Map<String, Object?>) {
    _writeJsonMap(buffer, value, depth);
  } else {
    throw CliError(
      kExitUnexpected,
      'unsupported JSON value type: ${value.runtimeType}',
    );
  }
}

void _writeJsonList(StringBuffer buffer, List<Object?> value, int depth) {
  if (value.isEmpty) {
    buffer.write('[]');
    return;
  }
  final indent = '  ' * (depth + 1);
  buffer.writeln('[');
  for (var i = 0; i < value.length; i++) {
    buffer.write(indent);
    _writeJson(buffer, value[i], depth + 1);
    if (i + 1 < value.length) {
      buffer.write(',');
    }
    buffer.writeln();
  }
  buffer.write('${'  ' * depth}]');
}

void _writeJsonMap(StringBuffer buffer, Map<String, Object?> value, int depth) {
  if (value.isEmpty) {
    buffer.write('{}');
    return;
  }
  final indent = '  ' * (depth + 1);
  final keys = value.keys.toList()..sort(compareJsonKeys);
  buffer.writeln('{');
  for (var i = 0; i < keys.length; i++) {
    buffer.write(indent);
    _writeJsonString(buffer, keys[i]);
    buffer.write(': ');
    _writeJson(buffer, value[keys[i]], depth + 1);
    if (i + 1 < keys.length) {
      buffer.write(',');
    }
    buffer.writeln();
  }
  buffer.write('${'  ' * depth}}');
}

/// Escapes exactly what Python's JSON encoder escapes with
/// `ensure_ascii=False`: quote, backslash and control characters below
/// U+0020; everything else is emitted literally.
void _writeJsonString(StringBuffer buffer, String value) {
  buffer.write('"');
  for (final rune in value.runes) {
    switch (rune) {
      case 0x22:
        buffer.write(r'\"');
      case 0x5C:
        buffer.write(r'\\');
      case 0x08:
        buffer.write(r'\b');
      case 0x09:
        buffer.write(r'\t');
      case 0x0A:
        buffer.write(r'\n');
      case 0x0C:
        buffer.write(r'\f');
      case 0x0D:
        buffer.write(r'\r');
      default:
        if (rune < 0x20) {
          buffer.write('\\u${rune.toRadixString(16).padLeft(4, '0')}');
        } else {
          buffer.writeCharCode(rune);
        }
    }
  }
  buffer.write('"');
}

/// Replaces [output] with [staging] atomically (both under the same parent);
/// on failure the previous output is restored untouched, so a failed
/// regeneration never destroys an existing bundle.
void swapIntoPlace(Directory staging, String output) {
  Directory? backup;
  if (Directory(output).existsSync()) {
    final reserved = Directory(parentOf(output)).createTempSync('.geo-backup-');
    reserved.deleteSync();
    Directory(output).renameSync(reserved.path);
    backup = Directory(reserved.path);
  }
  try {
    staging.renameSync(output);
  } on FileSystemException {
    if (backup != null && !Directory(output).existsSync()) {
      backup.renameSync(output);
      backup = null;
    }
    rethrow;
  }
  backup?.deleteSync(recursive: true);
}
