def convert(text: str):
    """Return (converted, changed_count). Unmapped chars pass through unchanged."""
    out, changed = [], 0
    for ch in text:
        mapped = S2T.get(ch) or S2T_EXTRA.get(ch)
        if mapped:
            out.append(mapped)
            changed += 1
        else:
            out.append(ch)
    return "".join(out), changed


def has_kana(text: str) -> bool:
    for ch in text:
        if "\u3040" <= ch <= "\u30ff":  # Hiragana + Katakana blocks
            return True
    return False
